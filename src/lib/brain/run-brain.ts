import { generateText } from "ai";
import { createGoogle, google } from "@ai-sdk/google";
import { config, hasGeminiConfig } from "../config";
import { analyseRequest } from "./request-analyser";
import { routeIntent } from "./intent-router";
import { selectModel } from "./model-selector";
import { safeSystemInstruction, safetyWarning, containsCredential } from "./safety-manager";
import { evaluateResponse } from "./response-evaluator";
import { usageInfo } from "./cost-manager";
import { logExecution } from "./execution-logger";
import { calculateFromRequest } from "../tools/calculator";
import type { BrainInput, BrainResponse, Citation } from "./types";

function provider() {
  let cursor = 0;
  const keys = config.geminiKeys;
  return createGoogle({ apiKey: () => {
    if (!keys.length) throw new Error("Gemini provider is not configured.");
    const key = keys[cursor % keys.length];
    cursor = (cursor + 1) % keys.length;
    return key;
  } });
}

function cleanOutput(text: string): string {
  return text
    .replace(/\bAIza[0-9A-Za-z_-]{20,}\b/g, "[credential removed]")
    .replace(/\bAQ\.[A-Za-z0-9_-]{20,}\b/g, "[credential removed]")
    .replace(/\bsk-(?:proj-|live-|svcacct-)?[A-Za-z0-9_-]{20,}\b/g, "[credential removed]")
    .replace(/\bgh[pousr]_[A-Za-z0-9]{20,}\b/g, "[credential removed]")
    .replace(/\bAKIA[0-9A-Z]{16}\b/g, "[credential removed]");
}

export async function runBrain(input: BrainInput): Promise<BrainResponse> {
  const startedAt = Date.now();
  const analysis = analyseRequest(input);
  const workflow = routeIntent(analysis.intent);
  const selected = selectModel(input, analysis);
  const warnings = safetyWarning(input.message);
  const base = { provider: "google", model: selected.displayName, workflow, citations: [] as Citation[], filesUsed: [] as string[], toolsUsed: [] as string[] };

  if (analysis.safetyLevel === "blocked") {
    return { ...base, responseText: "I can’t help with instructions that could cause harm. If someone may be in immediate danger, contact local emergency support.", usage: usageInfo(null, null, Date.now() - startedAt), warnings: ["Request blocked by the safety check."], executionStatus: "failed" };
  }
  if (containsCredential(input.message)) {
    return { ...base, responseText: "This message appears to contain a credential. I did not send or store it. Please revoke it and continue without sharing secrets.", usage: usageInfo(null, null, Date.now() - startedAt), warnings: ["Credential-like input was blocked before provider access."], executionStatus: "failed" };
  }
  if (analysis.requiresConfirmation) {
    return { ...base, responseText: "This request asks for an external action. OmniBrain does not perform that action automatically; confirm it through a connected integration first.", usage: usageInfo(null, null, Date.now() - startedAt), warnings: ["External action not executed."], executionStatus: "confirmation_required" };
  }
  const arithmetic = calculateFromRequest(input.message);
  if (arithmetic !== null && !analysis.needsWebSearch && !analysis.needsDocumentSearch) {
    return { ...base, responseText: arithmetic, provider: "OmniBrain calculator", model: "deterministic", workflow, toolsUsed: ["calculator"], usage: usageInfo(0, 0, Date.now() - startedAt), warnings, executionStatus: "completed" };
  }
  if (config.demoMode || !hasGeminiConfig()) {
    return { ...base, provider: "OmniBrain demo", model: "Mock Fast Model", responseText: `**Demo response**\n\nI classified this as **${analysis.intent.replaceAll("_", " ")}** and would use the **${selected.displayName}** model for the ${workflow} workflow.\n\n${input.message.length > 0 ? "Connect a live model provider in Settings to receive a real answer. This sample response was not generated by a model." : "Add a request to begin."}`, citations: [{ id: "demo-source-1", title: "Sample source (demo data)", url: "https://example.com/omnibrain-demo", sourceType: "demo", retrievedAt: new Date().toISOString() }], usage: usageInfo(null, null, Date.now() - startedAt), warnings: [...warnings, "Demo mode is active; no model call was made."], executionStatus: "demo" };
  }

  try {
    const googleProvider = provider();
    const prompt = input.message;
    const result = await generateText({
      model: googleProvider(selected.providerModelId),
      system: safeSystemInstruction(),
      prompt,
      maxOutputTokens: 1800,
      maxRetries: Math.min(4, config.geminiKeys.length),
      tools: analysis.needsWebSearch ? { google_search: google.tools.googleSearch({}), url_context: google.tools.urlContext({}) } : undefined,
    });
    const output = cleanOutput(result.text);
    const evaluated = evaluateResponse(output, analysis.responseFormat);
    const issue = containsCredential(result.text) ? ["Provider output contained a credential-like string and was redacted."] : [];
    logExecution({ requestId: input.conversationId, userId: input.userId, provider: "google", model: selected.providerModelId, workflow, durationMs: Date.now() - startedAt, status: "completed" });
    const citations = result.sources.flatMap((source, index) => "url" in source && typeof source.url === "string" ? [{ id: source.id || `web-${index}`, title: source.title || source.url, url: source.url, sourceType: "web" as const, retrievedAt: new Date().toISOString() }] : []);
    return { ...base, responseText: output, citations, toolsUsed: analysis.needsWebSearch ? ["web-search"] : [], usage: usageInfo(result.usage.inputTokens, result.usage.outputTokens, Date.now() - startedAt), warnings: [...warnings, ...evaluated.warnings, ...issue], executionStatus: "completed" };
  } catch {
    logExecution({ requestId: input.conversationId, userId: input.userId, provider: "google", model: selected.displayName, workflow, durationMs: Date.now() - startedAt, status: "failed" });
    return { ...base, responseText: "The selected model could not respond. Check the provider connection in Settings and try again.", usage: usageInfo(null, null, Date.now() - startedAt), warnings: [...warnings, "Provider failure was sanitized; no credentials or request text were logged."], executionStatus: "failed" };
  }
}
